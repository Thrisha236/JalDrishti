"""Secure handling of citizen photos.

Every upload is: size-capped, type-checked by its first bytes (not the file name or browser-declared type),
fully decoded by Pillow, rotated upright, downscaled, and re-encoded as a fresh JPEG. Re-encoding drops all
metadata (EXIF, GPS, camera serials) and anything appended to the file. Originals are never kept."""

import io
import uuid
import warnings
from pathlib import Path

from fastapi import HTTPException, UploadFile
from PIL import Image, ImageOps, UnidentifiedImageError

from . import config

Image.MAX_IMAGE_PIXELS = 40_000_000  # refuse decompression bombs well below Pillow's default

_SIGNATURES = (
    (b"\xff\xd8\xff", "jpeg"),
    (b"\x89PNG\r\n\x1a\n", "png"),
)


def _sniff(head: bytes) -> str | None:
    for sig, kind in _SIGNATURES:
        if head.startswith(sig):
            return kind
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "webp"
    return None


async def read_limited(upload: UploadFile, limit: int | None = None) -> bytes:
    limit = limit or config.MAX_PHOTO_BYTES
    data = await upload.read(limit + 1)
    if len(data) > limit:
        raise HTTPException(413, f"Photo must be under {limit // (1024 * 1024)} MB")
    return data


def clean_and_store(data: bytes, upload_dir: Path | None = None) -> str:
    """Validate, sanitise and save a photo. Returns the storage key (file name), never a public URL."""
    if not data:
        raise HTTPException(415, "Empty file")
    if _sniff(data[:16]) is None:
        raise HTTPException(415, "Only JPEG, PNG or WebP photos are accepted")
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data)) as probe:
                probe.verify()  # structural check; the image must be reopened afterwards
            with Image.open(io.BytesIO(data)) as img:
                img = ImageOps.exif_transpose(img)  # keep the photo upright before metadata is dropped
                img = img.convert("RGB")
                img.thumbnail((config.MAX_PHOTO_SIDE, config.MAX_PHOTO_SIDE))
                out = io.BytesIO()
                img.save(out, "JPEG", quality=85, optimize=True)  # no exif= argument: metadata is not copied
    except (UnidentifiedImageError, OSError, SyntaxError, Image.DecompressionBombError, Image.DecompressionBombWarning) as err:
        raise HTTPException(415, "The file is not a readable image") from err

    folder = upload_dir or config.UPLOAD_DIR
    folder.mkdir(parents=True, exist_ok=True)
    key = f"{uuid.uuid4().hex}.jpg"
    (folder / key).write_bytes(out.getvalue())
    return key


def path_for(key: str, upload_dir: Path | None = None) -> Path:
    folder = (upload_dir or config.UPLOAD_DIR).resolve()
    path = (folder / key).resolve()
    if path.parent != folder:  # storage keys are generated by us, but never trust a path blindly
        raise HTTPException(404, "Photo not found")
    return path


# Simulated image "analysis": a fixed observation per complaint category. Clearly labelled; no model runs.
SIMULATED_OBSERVATIONS = {
    "DIRTY_WATER": ("POSSIBLE_DISCOLOURED_WATER", "Possible discoloured water visible — a water test is recommended."),
    "BAD_SMELL": ("NO_VISIBLE_OBSERVATION", "Smell cannot be judged from a photo — a water test is recommended."),
    "DAMAGED_TAP": ("POSSIBLE_DAMAGED_FITTING", "Possible damaged tap or fitting visible — inspection recommended."),
}
DEFAULT_OBSERVATION = ("POSSIBLE_VISIBLE_LEAK", "Possible leakage visible near a pipe — inspection recommended.")
DISCLAIMER = "Prototype simulation. Not an AI diagnosis. A photo cannot show buried pipe condition."


def simulated_observation(category: str) -> tuple[str, str]:
    return SIMULATED_OBSERVATIONS.get(category, DEFAULT_OBSERVATION)
